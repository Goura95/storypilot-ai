# ============================================================
# STRING HELPER
# ============================================================

def _clean_string(
    value,
    default="",
) -> str:

    if value is None:
        return default

    if not isinstance(
        value,
        str,
    ):
        value = str(value)

    return value.strip()


# ============================================================
# LIST HELPER
# ============================================================

def _clean_string_list(
    value,
) -> list[str]:

    if not isinstance(
        value,
        list,
    ):
        return []

    result = []

    for item in value:

        cleaned = _clean_string(
            item
        )

        if cleaned:
            result.append(
                cleaned
            )

    return result


# ============================================================
# FRONTEND VALIDATION
# ============================================================

def _validate_frontend(
    value,
) -> dict:

    if not isinstance(
        value,
        dict,
    ):
        value = {}

    required = value.get(
        "required",
        False,
    )

    if not isinstance(
        required,
        bool,
    ):
        required = False

    return {
        "required": required,
        "changes": _clean_string_list(
            value.get(
                "changes",
                [],
            )
        ),
    }


