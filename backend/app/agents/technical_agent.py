# ============================================================
# GENERATE TECHNICAL ANALYSIS
# ============================================================

def analyze_technical(
    story_output: dict,
    business_analyst_output: dict,
) -> dict:

    if not isinstance(
        story_output,
        dict,
    ):
        raise ValueError(
            "story_output must be a dictionary."
        )

    if not isinstance(
        business_analyst_output,
        dict,
    ):
        raise ValueError(
            "business_analyst_output must be a dictionary."
        )

    prompt = _build_prompt(
        story_output=story_output,
        business_analyst_output=business_analyst_output,
    )

    try:

        completion = client.chat.completions.create(
            model=MODEL,
            temperature=0.1,
            response_format={
                "type": "json_object"
            },
            messages=[
                {
                    "role": "system",
                    "content": SYSTEM_PROMPT,
                },
                {
                    "role": "user",
                    "content": prompt,
                },
            ],
        )

    except Exception as exc:

        if is_rate_limit_error(exc):

            raise GroqRateLimitError(
                "Groq API rate limit exceeded. Please try again in a few minutes."
            ) from exc

        raise Exception(
            f"Technical Agent failed: {exc}"
        ) from exc

    content = (
        completion
        .choices[0]
        .message
        .content
    )

    if not content:
        raise Exception(
            "Technical Agent returned an empty response."
        )

    try:

        result = json.loads(
            content
        )

    except json.JSONDecodeError as exc:

        raise Exception(
            "Technical Agent returned invalid JSON."
        ) from exc

    return _validate_result(
        result
    )
