# ============================================================
# API VALIDATION
# ============================================================

def _validate_api(
    value,
) -> dict:

    if not isinstance(
        value,
        dict,
    ):
        value = {}

    required = value.get(
        "required",
        False,
    )

    if not isinstance(
        required,
        bool,
    ):
        required = False

    changes = value.get(
        "changes",
        [],
    )

    if not isinstance(
        changes,
        list,
    ):
        changes = []

    validated_changes = []

    for change in changes:

        if not isinstance(
            change,
            dict,
        ):
            continue

        acceptance_criteria_ids = (
            change.get(
                "acceptance_criteria_ids",
                [],
            )
        )

        if not isinstance(
            acceptance_criteria_ids,
            list,
        ):
            acceptance_criteria_ids = []

        acceptance_criteria_ids = [
            _clean_string(item)
            for item in acceptance_criteria_ids
            if _clean_string(item)
        ]

        validated_changes.append(
            {
                "method": _clean_string(
                    change.get(
                        "method"
                    )
                ),
                "purpose": _clean_string(
                    change.get(
                        "purpose"
                    )
                ),
                "authentication": _clean_string(
                    change.get(
                        "authentication"
                    )
                ),
                "authorization": _clean_string(
                    change.get(
                        "authorization"
                    )
                ),
                "acceptance_criteria_ids":
                    acceptance_criteria_ids,
            }
        )

    return {
        "required": required,
        "changes": validated_changes,
    }


